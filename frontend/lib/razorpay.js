/**
 * Safe client-side Razorpay Checkout Script Loader
 */
export function loadRazorpayScript() {
  return new Promise((resolve) => {
    if (typeof window === "undefined") {
      resolve(false);
      return;
    }

    if (window.Razorpay) {
      resolve(true);
      return;
    }

    const script = document.createElement("script");
    script.src = "https://checkout.razorpay.com/v1/checkout.js";
    script.async = true;
    script.onload = () => {
      resolve(true);
    };
    script.onerror = () => {
      console.warn("Could not load external Razorpay SDK script from CDN");
      resolve(false);
    };

    document.body.appendChild(script);
  });
}

